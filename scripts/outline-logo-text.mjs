// Build-time only: converts the logo's wordmark into SVG path data so the
// site never downloads a font just to draw the logo.
// Run with `npm run glyphs`; the output (src/components/Logo/glyphs.ts) is committed.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const font = (pkg, file) => {
  const buf = readFileSync(fileURLToPath(import.meta.resolve(`@fontsource/${pkg}/files/${file}`)));
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
};

const sans = font('josefin-sans', 'josefin-sans-latin-400-normal.woff');
const sansMed = font('josefin-sans', 'josefin-sans-latin-600-normal.woff');
const serif = font('cormorant-garamond', 'cormorant-garamond-latin-600-normal.woff');

const VIEW_W = 500;
const CX = VIEW_W / 2;
const r1 = (n) => Math.round(n * 10) / 10;

/**
 * Compact path serializer: relative commands, implicit command repeats, no
 * zero-length segments, minimal number separators. Deltas are taken between
 * already-rounded absolute points so rounding error never accumulates.
 */
function compactPath(commands, precision) {
  const k = 10 ** precision;
  const rd = (n) => Math.round(n * k) / k;
  const num = (n) => {
    const s = String(Math.round(n * k) / k);
    return s.replace(/^(-?)0\./, '$1.');
  };
  let out = '';
  let last = '';
  let prevNum = '';
  const emit = (cmd, vals) => {
    if (cmd !== last || cmd === 'm') {
      out += cmd;
      prevNum = '';
    }
    last = cmd;
    for (const v of vals) {
      const s = num(v);
      const needsSep = prevNum && !s.startsWith('-') && !(s.startsWith('.') && prevNum.includes('.'));
      out += (needsSep ? ' ' : '') + s;
      prevNum = s;
    }
  };
  let cx = 0;
  let cy = 0;
  let sx = 0;
  let sy = 0;
  for (const c of commands) {
    if (c.type === 'Z') {
      out += 'z';
      last = 'z';
      prevNum = '';
      cx = sx;
      cy = sy;
      continue;
    }
    const x = rd(c.x);
    const y = rd(c.y);
    if (c.type === 'M') {
      emit('m', [x - cx, y - cy]);
      sx = x;
      sy = y;
    } else if (c.type === 'L') {
      if (x === cx && y === cy) continue;
      emit('l', [x - cx, y - cy]);
    } else if (c.type === 'Q') {
      emit('q', [rd(c.x1) - cx, rd(c.y1) - cy, x - cx, y - cy]);
    } else if (c.type === 'C') {
      emit('c', [rd(c.x1) - cx, rd(c.y1) - cy, rd(c.x2) - cx, rd(c.y2) - cy, x - cx, y - cy]);
    }
    cx = x;
    cy = y;
  }
  return out;
}

/**
 * Lays out `tokens` (strings, or `null` for a dot separator) so the line is
 * exactly `width` wide and centred. Each unique glyph is emitted once and
 * referenced by <use>, which keeps repeated letters free.
 */
function layout({ f, tokens, tracking, width, baseline, dotGap = 0, precision = 0 }) {
  const measure = (size) => {
    const track = tracking * size;
    let x = 0;
    const items = [];
    tokens.forEach((tok, ti) => {
      if (tok === null) {
        const gap = dotGap * size;
        items.push({ dot: true, x: x + gap / 2 - track / 2 });
        x += gap;
        return;
      }
      for (const ch of tok) {
        const g = f.charToGlyph(ch);
        items.push({ ch, x });
        x += (g.advanceWidth / f.unitsPerEm) * size + track;
      }
    });
    return { items, w: x - tracking * size }; // drop trailing tracking
  };
  const probe = measure(100);
  const size = (100 * width) / probe.w;
  const { items, w } = measure(size);
  const x0 = CX - w / 2;

  const glyphs = {};
  let top = Infinity;
  let bottom = -Infinity;
  const uses = [];
  const dots = [];
  for (const it of items) {
    if (it.dot) {
      // Centre the dot on the cap height, like a middot.
      dots.push({ cx: r1(x0 + it.x), cy: r1(baseline - ((f.tables.os2.sCapHeight / f.unitsPerEm) * size) / 2), r: r1(size * 0.12) });
      continue;
    }
    // Glyphs are drawn on the baseline at x=0, so each <use> only needs an x.
    const p = f.getPath(it.ch, 0, baseline, size);
    glyphs[it.ch] ??= compactPath(p.commands, precision);
    const bb = f.getPath(it.ch, 0, 0, size).getBoundingBox();
    top = Math.min(top, baseline + bb.y1);
    bottom = Math.max(bottom, baseline + bb.y2);
    uses.push([it.ch, Math.round(x0 + it.x)]);
  }
  return { glyphs, uses, baseline, box: { y: Math.floor(top) - 1, h: Math.ceil(bottom - top) + 2 }, dots };
}

const studio = layout({ f: sans, tokens: ['STUDIO'], tracking: 0.5, width: 215, baseline: 258 });
const akaar = layout({ f: serif, tokens: ['akaar'], tracking: 0.62, width: 400, baseline: 338, precision: 1 });
const tagline = layout({
  f: sansMed,
  tokens: ['CREATE', null, 'CONNECT', null, 'EXPRESS'],
  tracking: 0.2,
  width: 480,
  baseline: 384,
  dotGap: 1.2,
});

const out = `// Generated by scripts/outline-logo-text.mjs — do not edit by hand.
export type Line = {
  glyphs: Record<string, string>;
  uses: [string, number][];
  baseline: number;
  box: { y: number; h: number };
  dots: { cx: number; cy: number; r: number }[];
};
export const studio: Line = ${JSON.stringify(studio)};
export const akaar: Line = ${JSON.stringify(akaar)};
export const tagline: Line = ${JSON.stringify(tagline)};
`;
const dest = new URL('../src/components/Logo/glyphs.ts', import.meta.url);
writeFileSync(dest, out);
console.log(`glyphs.ts written (${out.length} bytes)`);

// ---- Handwritten hero note (Caveat), one kerned path per line ----
const script = font('caveat', 'caveat-latin-600-normal.woff');
const SCRIPT_SIZE = 40;
const LEAD = 44;
const scriptLines = ['Shape it.', 'Personalize it.', 'Make it yours.'].map((text, i) => {
  const baseline = 34 + i * LEAD;
  const p = script.getPath(text, 0, baseline, SCRIPT_SIZE, { kerning: true });
  const bb = p.getBoundingBox();
  return { d: compactPath(p.commands, 0), w: Math.ceil(bb.x2), y: Math.floor(bb.y1) - 2, h: Math.ceil(bb.y2 - bb.y1) + 4 };
});
const scriptOut = `// Generated by scripts/outline-logo-text.mjs — do not edit by hand.
export const noteLines: { d: string; w: number; y: number; h: number }[] = ${JSON.stringify(scriptLines)};
`;
writeFileSync(new URL('../src/components/Hero/note-glyphs.ts', import.meta.url), scriptOut);
console.log(`note-glyphs.ts written (${scriptOut.length} bytes)`);
